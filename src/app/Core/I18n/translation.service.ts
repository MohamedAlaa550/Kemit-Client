@Injectable({ providedIn: 'root' })
export class TranslationService {
  private readonly document = inject(DOCUMENT);
  private readonly platformId = inject(PLATFORM_ID);
  readonly locale = signal<Locale>(this.savedLocale());

  constructor() {
    effect(() => {
      const locale = this.locale();
      this.document.documentElement.lang = locale;
      this.document.documentElement.dir = locale === 'ar' ? 'rtl' : 'ltr';
      if (isPlatformBrowser(this.platformId)) localStorage.setItem('kemit_locale', locale);
    });
  }

  toggle() {
    this.locale.update((value) => (value === 'ar' ? 'en' : 'ar'));
  }
  translate(key: string) {
    const value = dictionary[key];
    return value ? value[this.locale() === 'ar' ? 0 : 1] : key;
  }
  private savedLocale(): Locale {
    return isPlatformBrowser(this.platformId) && localStorage.getItem('kemit_locale') === 'en'
      ? 'en'
      : 'ar';
  }
}
